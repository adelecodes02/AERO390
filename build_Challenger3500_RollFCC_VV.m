
% Creates a Simulink model with separate FCC allocation and aircraft/actuator plant.
% Run this script in MATLAB with Simulink and Stateflow available.
%
% Model inputs:
%   pilotRoll       normalized pilot roll command [-1,+1]
%   qbarScale       normalized dynamic-pressure scale [0,1] (1 = design case)
%   aileronJam      1 = aileron jam/frozen; 0 = healthy
%   spoilerJam      1 = spoiler jam/frozen; 0 = healthy
%   reset           1 = reset plant states
%
% IMPORTANT: all surface limits, actuator rates/time constants, qbar scaling,
% aerodynamic effectiveness, and actuator geometry are provisional placeholders.
% Replace them with approved aircraft/interface data before drawing conclusions.

clearvars -except keepWorkspace;
clc;

mdl = 'Challenger3500_RollFCC_VV';
if bdIsLoaded(mdl), close_system(mdl,0); end
if exist([mdl '.slx'],'file'), delete([mdl '.slx']); end

% ---------------------- Workbook-derived parameters -----------------------
P = struct();
P.Ixx_kgm2 = 181123.58;             % Roll Rate sheet
P.bankAngle_rad = 1.0471975512;     % 60 deg, Roll Rate sheet
P.bankTime_s = 7.0;                 % Roll Rate sheet
P.requiredMoment_Nm = 7741.7212;    % Roll Rate sheet
P.aileronForce_N = 385.1603;        % Roll Rate sheet
P.spoilerForce_N = 192.5801;        % Roll Rate sheet
P.aileronArm_m = 8.6;               % Roll Rate sheet (moment arm assumption)
P.spoilerArm_m = 5.8;               % Roll Rate sheet (moment arm assumption)
P.aileronHingeMoment_Nm = 1560.336; % Superseeded sheet, comparison result
P.aileronSpan_m = 0.740537;         % Inboard Aileron 2D sheet
P.aileronArea_m2 = 0.341221;        % Inboard Aileron 2D sheet
P.aileronChordIn_m = 0.486026;      % Inboard Aileron 2D sheet
P.aileronChordOut_m = 0.435524;     % Inboard Aileron 2D sheet
P.hingeArmIn_m = 0.145808;          % Inboard Aileron 2D sheet, cb
P.hingeArmOut_m = 0.130657;         % Inboard Aileron 2D sheet, cb
P.hingeCoefficient = 0.0150399;     % Superseeded sheet
P.hingeLoad_N = 10812.825;          % Superseeded sheet


P.surfaceLimit_deg = 15.0;          % provisional placeholder; confirm actual stops
P.actuatorRate_deg_s = 20.0;        % provisional placeholder; replace with sizing result
P.actuatorTau_s = 0.12;             % provisional placeholder
P.actuatorArm_m = 0.10;             % provisional placeholder; actuator geometry missing
P.Ts_s = 0.01;
P.maxQbarScale = 1.0;
P.aileronMomentAtFullDefl_Nm = P.aileronForce_N * P.aileronArm_m;
P.spoilerMomentAtFullDefl_Nm = P.spoilerForce_N * P.spoilerArm_m;
P.availableMoment_Nm = P.aileronMomentAtFullDefl_Nm + P.spoilerMomentAtFullDefl_Nm;
P.availableRollAccel_rad_s2 = P.availableMoment_Nm / P.Ixx_kgm2;
P.predictedBankTime_s = sqrt(2*P.bankAngle_rad/P.availableRollAccel_rad_s2);
P.requiredAvgRollRate_deg_s = rad2deg(P.bankAngle_rad)/P.bankTime_s;
P.requiredPeakRollRate_deg_s = 2*P.requiredAvgRollRate_deg_s; % constant acceleration from rest

assignin('base','P_RollFCC',P);

fprintf('\n--- Workbook consistency check ---\n');
fprintf('Aileron roll moment estimate: %.1f N.m\n',P.aileronMomentAtFullDefl_Nm);
fprintf('Spoiler roll moment estimate: %.1f N.m\n',P.spoilerMomentAtFullDefl_Nm);
fprintf('Combined estimated moment: %.1f N.m\n',P.availableMoment_Nm);
fprintf('Moment required by 60 deg / 7 s calculation: %.1f N.m\n',P.requiredMoment_Nm);
fprintf('Predicted bank time from listed surface forces/arms: %.2f s\n',P.predictedBankTime_s);
fprintf('Required average roll rate: %.2f deg/s; constant-accel peak: %.2f deg/s\n\n', ...
    P.requiredAvgRollRate_deg_s,P.requiredPeakRollRate_deg_s);

% ----------------------------- Create model -------------------------------
new_system(mdl);
open_system(mdl);
set_param(mdl,'StopTime','12','Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(P.Ts_s),'SolverType','Fixed-step', ...
    'SaveOutput','on','SaveTime','on','SignalLogging','on');

% Root inputs
rootInputs = {'pilotRoll','qbarScale','aileronJam','spoilerJam','reset'};
for k=1:numel(rootInputs)
    b = add_block('simulink/Ports & Subsystems/In1',[mdl '/' rootInputs{k}], ...
        'Position',[35 45+65*(k-1) 65 59+65*(k-1)]);
    set_param(b,'Port',num2str(k));
end

% FCC subsystem: pilot command allocation and single-failure reconfiguration
fccScript = [
"function [ailCmdDeg,spoCmdDeg,faultCode,remainingAuthority] = fcn(pilotRoll,qbarScale,aileronJam,spoilerJam,reset)" newline ...
"%#codegen" newline ...
"% Equivalent differential surface commands. Positive signs must create the same roll direction." newline ...
"lim = 15.0; % provisional surface limit; replace with approved data" newline ...
"u = min(max(pilotRoll,-1.0),1.0);" newline ...
"aileronJam = aileronJam > 0.5; spoilerJam = spoilerJam > 0.5;" newline ...
"if reset > 0.5" newline ...
"    ailCmdDeg = 0; spoCmdDeg = 0; faultCode = 0; remainingAuthority = 1;" newline ...
"elseif ~aileronJam && ~spoilerJam" newline ...
"    ailCmdDeg = lim*u; spoCmdDeg = lim*u; faultCode = 0; remainingAuthority = 1;" newline ...
"elseif aileronJam && ~spoilerJam" newline ...
"    ailCmdDeg = 0; spoCmdDeg = lim*u; faultCode = 1; remainingAuthority = 0.252;" newline ...
"elseif ~aileronJam && spoilerJam" newline ...
"    ailCmdDeg = lim*u; spoCmdDeg = 0; faultCode = 2; remainingAuthority = 0.748;" newline ...
"else" newline ...
"    ailCmdDeg = 0; spoCmdDeg = 0; faultCode = 3; remainingAuthority = 0;" newline ...
"end" newline ...
"% qbarScale is carried as a plant input; command allocation is not scheduled yet." newline ...
"end"
];
makeSubsystem(mdl,'FCC_Allocation',rootInputs, ...
    {'ailCmdDeg','spoCmdDeg','faultCode','remainingAuthority'},fccScript,[210 50 455 370]);

% Plant subsystem: actuator rate limit + first-order response + roll rigid-body model
plantInputs = {'ailCmdDeg','spoCmdDeg','qbarScale','aileronJam','spoilerJam','reset'};
plantScript = [
"function [ailPosDeg,spoPosDeg,rollRateDeg_s,rollAngleDeg,rollMomentNm,ailHingeMomentNm,ailActuatorForceN,spoilerLoadValid] = fcn(ailCmdDeg,spoCmdDeg,qbarScale,aileronJam,spoilerJam,reset)" newline ...
"%#codegen" newline ...
"% Discrete equivalent actuator and roll-response plant. Not a detailed hydraulic model." newline ...
"persistent ailState spoState rollRate rollAngle" newline ...
"Ts = 0.01; lim = 15.0; rate = 20.0; tau = 0.12;" newline ...
"Ixx = 181123.58;" newline ...
"MAilFull = 385.1602588*8.6;" newline ...
"MSpoFull = 192.5801294*5.8;" newline ...
"MHingeFull = 1560.335954;" newline ...
"actArm = 0.10; % placeholder only; replace with measured actuator moment arm" newline ...
"if isempty(ailState) || reset > 0.5" newline ...
"    ailState = 0; spoState = 0; rollRate = 0; rollAngle = 0;" newline ...
"end" newline ...
"q = min(max(qbarScale,0.0),1.0);" newline ...
"if aileronJam > 0.5" newline ...
"    % Jam holds the last physical position." newline ...
"else" newline ...
"    target = min(max(ailCmdDeg,-lim),lim);" newline ...
"    lagged = ailState + (Ts/(tau+Ts))*(target-ailState);" newline ...
"    step = min(max(lagged-ailState,-rate*Ts),rate*Ts);" newline ...
"    ailState = min(max(ailState+step,-lim),lim);" newline ...
"end" newline ...
"if spoilerJam > 0.5" newline ...
"else" newline ...
"    target = min(max(spoCmdDeg,-lim),lim);" newline ...
"    lagged = spoState + (Ts/(tau+Ts))*(target-spoState);" newline ...
"    step = min(max(lagged-spoState,-rate*Ts),rate*Ts);" newline ...
"    spoState = min(max(spoState+step,-lim),lim);" newline ...
"end" newline ...
"ailPosDeg = ailState; spoPosDeg = spoState;" newline ...
"rollMomentNm = q*(MAilFull*(ailState/lim) + MSpoFull*(spoState/lim));" newline ...
"rollAccel = rollMomentNm/Ixx;" newline ...
"rollRate = rollRate + rollAccel*Ts;" newline ...
"rollAngle = rollAngle + rollRate*Ts;" newline ...
"rollRateDeg_s = rollRate*180/pi; rollAngleDeg = rollAngle*180/pi;" newline ...
"ailHingeMomentNm = q*MHingeFull*abs(ailState/lim);" newline ...
"ailActuatorForceN = ailHingeMomentNm/actArm;" newline ...
"% Spoiler hinge-moment/actuator geometry is absent from the supplied calculation file." newline ...
"spoilerLoadValid = 0;" newline ...
"end"
];
makeSubsystem(mdl,'Actuation_and_Roll_Plant',plantInputs, ...
    {'ailPosDeg','spoPosDeg','rollRateDeg_s','rollAngleDeg','rollMomentNm', ...
     'ailHingeMomentNm','ailActuatorForceN','spoilerLoadValid'},plantScript,[570 50 900 430]);

% Wire root inputs to FCC and plant
for k=1:numel(rootInputs)
    add_line(mdl,[rootInputs{k} '/1'],['FCC_Allocation/' num2str(k)],'autorouting','on');
end
% FCC command outputs to plant; qbar and failure inputs go directly to plant
add_line(mdl,'FCC_Allocation/1','Actuation_and_Roll_Plant/1','autorouting','on');
add_line(mdl,'FCC_Allocation/2','Actuation_and_Roll_Plant/2','autorouting','on');
add_line(mdl,'qbarScale/1','Actuation_and_Roll_Plant/3','autorouting','on');
add_line(mdl,'aileronJam/1','Actuation_and_Roll_Plant/4','autorouting','on');
add_line(mdl,'spoilerJam/1','Actuation_and_Roll_Plant/5','autorouting','on');
add_line(mdl,'reset/1','Actuation_and_Roll_Plant/6','autorouting','on');

% Expose all model outputs as Outports
outNames = {'ailCmdDeg','spoCmdDeg','faultCode','remainingAuthority', ...
    'ailPosDeg','spoPosDeg','rollRateDeg_s','rollAngleDeg','rollMomentNm', ...
    'ailHingeMomentNm','ailActuatorForceN','spoilerLoadValid'};
for k=1:4
    b=add_block('simulink/Ports & Subsystems/Out1',[mdl '/' outNames{k}], ...
        'Position',[1000 55+45*(k-1) 1030 69+45*(k-1)]);
    set_param(b,'Port',num2str(k));
    add_line(mdl,['FCC_Allocation/' num2str(k)],[outNames{k} '/1'],'autorouting','on');
end
for k=5:numel(outNames)
    b=add_block('simulink/Ports & Subsystems/Out1',[mdl '/' outNames{k}], ...
        'Position',[1000 270+38*(k-5) 1030 284+38*(k-5)]);
    set_param(b,'Port',num2str(k));
    add_line(mdl,['Actuation_and_Roll_Plant/' num2str(k-4)],[outNames{k} '/1'],'autorouting','on');
end

% Documentation annotation
note = sprintf(['RESEARCH V&V MODEL ONLY - NOT FLIGHT SOFTWARE\\n' ...
    'Workbook-derived roll moments: aileron %.1f N.m; spoiler %.1f N.m; total %.1f N.m\\n' ...
    'Roll-rate worksheet target: 60 deg in 7 s; required moment %.1f N.m\\n' ...
    'Predicted bank time from listed forces/arms: %.2f s\\n' ...
    'Spoiler hinge moment and actuator arm are missing; placeholder parameters require replacement.'], ...
    P.aileronMomentAtFullDefl_Nm,P.spoilerMomentAtFullDefl_Nm, ...
    P.availableMoment_Nm,P.requiredMoment_Nm,P.predictedBankTime_s);
Simulink.Annotation(mdl,note);
set_param(mdl,'ZoomFactor','FitSystem');
save_system(mdl,[mdl '.slx']);
fprintf('Created %s.slx\n',mdl);

% ----------------------------- Local helper -------------------------------
function makeSubsystem(mdl,name,inNames,outNames,script,pos)
sub=[mdl '/' name];
add_block('simulink/Ports & Subsystems/Subsystem',sub,'Position',pos);
% Remove default In1/Out1
try, delete_block([sub '/In1']); end %#ok<TRYNC>
try, delete_block([sub '/Out1']); end %#ok<TRYNC>
for i=1:numel(inNames)
    b=add_block('simulink/Ports & Subsystems/In1',[sub '/' inNames{i}], ...
        'Position',[25 35+45*(i-1) 55 49+45*(i-1)]);
    set_param(b,'Port',num2str(i));
end
mf=[sub '/Logic'];
add_block('simulink/User-Defined Functions/MATLAB Function',mf, ...
    'Position',[175 70 360 230]);
rt=sfroot;
chart=rt.find('-isa','Stateflow.EMChart','Path',mf);
chart.Script=char(script);
for i=1:numel(outNames)
    b=add_block('simulink/Ports & Subsystems/Out1',[sub '/' outNames{i}], ...
        'Position',[430 35+42*(i-1) 460 49+42*(i-1)]);
    set_param(b,'Port',num2str(i));
end
for i=1:numel(inNames)
    add_line(sub,[inNames{i} '/1'],['Logic/' num2str(i)],'autorouting','on');
end
for i=1:numel(outNames)
    add_line(sub,['Logic/' num2str(i)],[outNames{i} '/1'],'autorouting','on');
end
end
